// cva only concatenates, so a className passed to it (`bg-x` over the
// variant's own `bg-y`) would ship both and the stylesheet order would pick
// the winner. Links styled as buttons call this directly instead of going
// through <Button>, so the merge has to happen here, not only in <Button>.
function buttonVariants(props?: Parameters<typeof buttonVariantsBase>[0]) {
  return cn(buttonVariantsBase(props))
}

// `loading` is the one thing every action button in this app needed and
// didn't have: a spinner, not just changing text, so a tap reads as
// "working" the instant it happens rather than however long it takes the
// label to catch up. Centralized here instead of fourteen separate
// Loader2-plus-animate-spin blocks. Implies disabled, a loading button is
// never clickable regardless of what's passed in.
function Button({
  className,
  variant = "default",
  size = "default",
  loading = false,
  disabled,
  children,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants> & { loading?: boolean }) {
  return (
    <ButtonPrimitive
      data-slot="button"
      disabled={disabled || loading}
      aria-busy={loading || undefined}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    >
      {loading && <Loader2 className="animate-spin" aria-hidden />}
      {children}
    </ButtonPrimitive>
  )
}

